class Reject(Exception):
    """A failure: the evaluation is rejected (DESIGN §6.3)."""


# ---- the contract's statement functions (Contract/Recursion.lean), re-implemented -------------

def H(cfg_hash, b):
    """`cfg.hash.run` (Contract/Compile.lean `HashId.run`): the menu has BLAKE2s-256 only."""
    if cfg_hash != "blake2s":
        raise Reject(f"hash {cfg_hash!r} is not on the menu")
    return hashlib.blake2s(bytes(b)).digest()

def stmt_bytes(x):
    """`stmtBytes`: the 32 elements, 8 bytes little-endian each."""
    return b"".join((v % U64).to_bytes(8, "little") for v in x)

def stmt_of_bytes(b):
    assert len(b) == 256
    return list(struct.unpack("<32Q", b))

def digest_to_slot(d):
    """`digestToSlot`: limb j = digest bytes 8j .. 8j+7, little-endian."""
    return list(struct.unpack("<4Q", d))

def node_stmt(h, dC, dL, t1, t2, x1, x2):
    """`nodeStmt cfg vkC vkL t1 t2 x1 x2` with `dC = D vkC`, `dL = D vkL`: d0 = dC, d1 = dL,
    d2 = H(x1 || x2), d3 = (tag t1, tag t2, 0, 0), d4 .. d7 = 0 (S5-A8, S5-A11)."""
    return (digest_to_slot(dC) + digest_to_slot(dL) + digest_to_slot(H(h, stmt_bytes(x1) + stmt_bytes(x2)))
            + [TAGK[t1], TAGK[t2], 0, 0] + [0] * 16)

def pair_up(h, dC, dL, t, xs):
    """`pairUp`: adjacent statements aggregated in order, all tagged `t`; None on an odd count."""
    if len(xs) % 2:
        return None
    return [node_stmt(h, dC, dL, t, t, xs[i], xs[i + 1]) for i in range(0, len(xs), 2)]

def tree_root(h, dC, dL, d, xs):
    """`treeRoot cfg vkC vkL d xs`: level 1 over leaves, above over nodes; None unless 2^d leaves."""
    t = LEAF
    for _ in range(d):
        xs = pair_up(h, dC, dL, t, xs)
        if xs is None:
            return None
        t = NODE
    return xs[0] if len(xs) == 1 else None

def chain_stmt(secret, n):
    """The statement of `R_chain(y, n; s)`: (y0, y1, y2, y3, n, 0, ...), y = blake2s256^n(s) (S6-A3)."""
    y = secret
    for _ in range(n):
        y = hashlib.blake2s(y).digest()
    return digest_to_slot(y) + [n] + [0] * 27


# ---- processes -------------------------------------------------------------------------------

class Runner:
    def __init__(self, cfg, workdir, log):
        self.cfg, self.workdir, self.log = cfg, workdir, log
        # hidden from every sandboxed process: the run directory (other steps, the secrets of the
        # other chains, layouts; bwrap-landrun.sh --hide). The secrets exist nowhere else (S9I-m4).
        self.hidden = [workdir]
        self.eval_cap = None                   # the derived whole-evaluation cap (S9F-M5), seconds
        for exe in (cfg["verify"][0], cfg["index"][0], cfg["prover"][0]):
            path = os.path.realpath(shutil.which(exe) or exe)
            if path.startswith(workdir + os.sep):
                raise Reject(f"{exe} lies inside the hidden run directory")
        # S6b-m3: a step sees only /usr, /etc, a fresh /tmp (bwrap-landrun.sh --minimal-root), its
        # own directory, and read-only: the executables' directories, the files the prover's argv
        # names, and `sandbox_ro`
        ro = set()
        for argv in (cfg["verify"], cfg["index"], cfg["prover"]):
            for a in argv:
                q = shutil.which(a) if os.sep not in a else a
                if q and os.path.exists(q):
                    ro.add(os.path.dirname(os.path.realpath(q)))
        self.ro = sorted(r for r in ro | set(cfg.get("sandbox_ro") or []) if not r.startswith(("/usr", "/etc")))
        for r in self.ro:      # (a parent of the run directory is fine: the hides come after the binds)
            if r == workdir or r.startswith(workdir + os.sep):
                raise Reject(f"read-only path {r} lies inside the hidden run directory")
        # S6b-m1: every sandboxed step runs in its own cgroup with the memory cap (systemd-run)
        mem = cfg["budgets"]["mem_kb"] * 1024
        self.cgroup = ["systemd-run", "--user", "--scope", "-q", "-p", f"MemoryMax={mem}",
                       "-p", "MemorySwapMax=0", "-p", "OOMPolicy=continue", "--"]
        self.t0 = time.perf_counter()
        self.counter = 0

    def fresh(self, name):
        """A fresh step directory (never reused)."""
        self.counter += 1
        d = os.path.join(self.workdir, f"{self.counter:05d}-{name}")
        os.mkdir(d, 0o700)
        return d

    def check_eval_budget(self):
        if self.eval_cap is not None and time.perf_counter() - self.t0 > self.eval_cap:
            raise Reject(f"the evaluation exceeded its derived budget of {self.eval_cap:.0f} s (S9F-M5)")

    def run(self, argv, cwd, budget, what):
        """Run `argv` in `cwd`; return (exit code, wall s, peak KB). With a sandbox (always, under
        `run`, S6b-M1) the process runs in its own cgroup with `MemoryMax` = the cap (S6b-m1), inside
        `bwrap-landrun.sh --minimal-root` (S6b-m3); a small organiser shell in the cgroup, outside
        the sandbox, records the wall time of the sandboxed process (`date +%s%N` around it) and the
        cgroup's `memory.peak` (the whole process tree) and `oom_kill` count (`memory.events`) into a
        directory the sandbox does not see. `OOMPolicy=continue`: with systemd's default (`stop`) an
        OOM kill stops the whole scope, organiser shell included, and nothing is recorded.
        Without a sandbox (`measure-noise.py` only) the wall time is the spawn-to-exit time and the
        peak `os.wait4`'s `ru_maxrss` of the direct child."""
        self.check_eval_budget()
        sb = self.cfg["sandbox"]
        meta = None
        env = None
        if sb:
            meta = cwd + ".meta"                      # beside the step: hidden with the run directory
            os.mkdir(meta, 0o700)
            pre = [sb, "--minimal-root"]
            for r in self.ro:
                pre += ["--ro", r]
            for h in self.hidden:
                pre += ["--hide", h]
            pre += ["--env", "PATH", "--rwx", cwd, "--"]
            script = ('t0=$(date +%s%N); "$@"; rc=$?; t1=$(date +%s%N); '
                      'cg=$(cut -d: -f3 /proc/self/cgroup); '
                      'cat "/sys/fs/cgroup$cg/memory.peak" > "$RF_META/peak" 2>/dev/null; '
                      'sed -n "s/^oom_kill //p" "/sys/fs/cgroup$cg/memory.events" > "$RF_META/oom" 2>/dev/null; '
                      'echo $((t1 - t0)) > "$RF_META/wall"; exit $rc')
            argv = self.cgroup + ["sh", "-c", script, "rf-step"] + pre + list(argv)
            env = dict(os.environ, RF_META=meta)
        out = open(os.path.join(cwd, ".stdout"), "wb")
        err = open(os.path.join(cwd, ".stderr"), "wb")
        fired = []
        start = time.perf_counter_ns()
        p = subprocess.Popen(argv, cwd=cwd, stdin=subprocess.DEVNULL, stdout=out, stderr=err,
                             start_new_session=True, env=env)
        def kill():
            fired.append(True)
            try:
                os.killpg(p.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        timer = threading.Timer(budget, kill)
        timer.start()
        _, status, ru = os.wait4(p.pid, 0)       # blocking: the end of the timed region is exact
        wall = (time.perf_counter_ns() - start) / 1e9
        timer.cancel()
        p.returncode = os.waitstatus_to_exitcode(status)
        out.close(); err.close()
        if fired:
            raise Reject(f"{what}: timeout after {budget} s")
        cap = self.cfg["budgets"]["mem_kb"]
        peak = ru.ru_maxrss
        if meta:
            try:
                wall = int(open(os.path.join(meta, "wall")).read()) / 1e9
                peak = int(open(os.path.join(meta, "peak")).read()) // 1024
                oom = int(open(os.path.join(meta, "oom")).read())
            except (OSError, ValueError):
                raise Reject(f"{what}: no measurement from the step's cgroup (exit {p.returncode})")
            shutil.rmtree(meta, ignore_errors=True)
            if oom:       # any process of the step killed by the kernel at MemoryMax, exit code aside
                raise Reject(f"{what}: killed at the memory cap of {cap} KB (cgroup MemoryMax, "
                             f"{oom} oom_kill, exit {p.returncode})")
        if peak > cap:
            raise Reject(f"{what}: peak memory {peak} KB above {cap} KB")
        return p.returncode, wall, peak

    def stage(self, name, files, layout=None):
        """A fresh step directory with `files` ({name: bytes or str}) and `layout` as layout.json."""
        d = self.fresh(name)
        if layout:
            shutil.copyfile(layout, os.path.join(d, "layout.json"))
        for f, data in files.items():
            write(d, f, data)
        return d

    def prove(self, name, mode, layout, files, budget, what):
        """The prover (`prover` + `mode`) in a fresh step directory: (proof bytes, wall s, maxrss KB)."""
        d = self.stage(name, files, layout)
        rc, wall, rss = self.run(self.cfg["prover"] + [mode], d, budget, what)
        if rc != 0 or not os.path.isfile(os.path.join(d, "proof.bin")):
            raise Reject(f"{what}: the prover failed (exit {rc}) or wrote no proof.bin")
        proof = open(os.path.join(d, "proof.bin"), "rb").read()
        self.cleanup(d)
        return proof, wall, rss

    def run_verify(self, name, vkc, x, tape, budget, what):
        """`VERIFY vkc.bin stmt.bin proof.bin` in a fresh step directory: (exit code, wall s, maxrss KB)."""
        d = self.stage(name, {"vkc.bin": vkc, "stmt.bin": stmt_bytes(x), "proof.bin": tape})
        rc, wall, rss = self.run(self.cfg["verify"] + ["vkc.bin", "stmt.bin", "proof.bin"], d, budget, what)
        self.cleanup(d)
        return rc, wall, rss

    def verify(self, vkc, x, proof, budget, what, cap=None):
        """`NARG` on (key bytes, statement, tape) in a fresh directory; must accept."""
        if cap is not None and len(proof) > cap:
            raise Reject(f"{what}: proof of {len(proof)} bytes above the cap {cap}")
        rc, wall, rss = self.run_verify("verify", vkc, x, proof, budget, what)
        if rc != 0:
            raise Reject(f"{what}: the proof does not verify (exit {rc})")
        return wall, rss

    def cleanup(self, d):
        if not self.cfg.get("keep"):
            shutil.rmtree(d, ignore_errors=True)


def write(d, name, data):
    with open(os.path.join(d, name), "wb" if isinstance(data, bytes) else "w") as f:
        f.write(data)

def median(xs):
    return statistics.median(xs) if xs else None

def step_record(pw, prss, vw, vrss, proof):
    """A step's measurements; its score is prover + verifier wall time (§6.4)."""
    return {"prove_s": pw, "verify_s": vw, "score_s": pw + vw, "proof_bytes": len(proof),
            "prove_maxrss_kb": prss, "verify_maxrss_kb": vrss}

def level_group(lv):
    """The level groups of `S_rec` (S9I-M2): level 2, level 3, and levels >= 4 pooled (7 steps for
    a 64-leaf tree), so that no group is a single step."""
    return "2" if lv == 2 else "3" if lv == 3 else "4+"

def fresh_secrets(count):
    """`count` fresh chain starts from the OS's randomness (S9I-m4): never read from a file."""
    return [os.urandom(32) for _ in range(count)]


class Fatal(Reject):
    """A failure no board survives (a canary the verifier accepts: the executable itself is wrong)."""


# ---- the evaluation --------------------------------------------------------------------------

class Evaluation:
    """One entry's evaluation (§6.3): `prepare` (classes, instances, the prover build, indexing;
    untimed), `run_once` per run (leaves, tree, root; timed, with canaries), `finish` (per-board
    verdicts and scores, DoS). A failure shared by every board (instances, indexing of the leaf
    layouts, a tree chain's leaf, a canary, the evaluation budget, the DoS column) raises
    `Reject`; a failure of one board (board L: a leaf-board chain, the 2^17-byte cap; boards R and
    W: `C_V`'s key, the claimed digests, a tree step, the root) marks that board REJECT and the
    others go on (S7-M2). `secrets`: the tree chains' starts, shared by both entries of a paired
    comparison (`compare`); `None`: fresh ones."""

    def __init__(self, cfg, workdir, res, log, secrets=None):
        self.cfg, self.res, self.log, self.secrets_in = cfg, res, log, secrets
        self.R = Runner(cfg, workdir, log)
        self.workdir = workdir
        self.h = cfg["cfg"]["hash"]
        self.boards = set(cfg["boards"]) | ({"W"} if "R" in cfg["boards"] else set())
        self.tree_bs = {"R", "W"} if "R" in self.boards else set()
        self.failed = {}                                 # board -> reason
        self.runs, self.canaries = [], 0

    def fail(self, bs, reason):
        for b in bs:
            if b in self.boards and b not in self.failed:
                self.failed[b] = reason
                self.log(f"board {b}: REJECT ({reason})")

    def prepare(self, runs):
        cfg, R = self.cfg, self.R
        tree_n, tree_leaves = cfg["tree"]["n"], cfg["tree"]["leaves"]
        depth = tree_leaves.bit_length() - 1
        if tree_leaves != 2 ** depth or depth < 1:
            raise Reject(f"tree.leaves = {tree_leaves} is not a power of two >= 2")
        self.tree_n, self.tree_leaves, self.depth = tree_n, tree_leaves, depth
        # classes (S6-A1, S7-M2): the declared class must admit L_chain(tree.n); a leaf-board size
        # whose layout needs a larger class than declared is skipped, not failed
        k, classes = cfg["k"], {int(n): c for n, c in cfg["classes"].items()}
        if tree_n not in classes:
            raise Reject(f"no class known for L_chain({tree_n}) (config classes)")
        if k < classes[tree_n]:
            raise Reject(f"the declared class k = {k} is below the class {classes[tree_n]} of the benchmark "
                         f"layout L_chain({tree_n}): no board can be run")
        chains, skipped = [tree_n] * tree_leaves, {}
        if "L" in self.boards:
            for n, count in sorted(cfg["leafboard"].items(), key=lambda kv: int(kv[0])):
                n = int(n)
                if n not in classes:
                    raise Reject(f"no class known for L_chain({n}) (config classes)")
                if classes[n] > k:
                    skipped[str(n)] = f"L_chain({n}) needs class {classes[n]} > declared k = {k}"
                    self.log(f"board L: skipping n = {n} ({skipped[str(n)]})")
                    continue
                chains += [n] * count
        given = self.secrets_in or []
        self.secrets = given[:len(chains)] + fresh_secrets(len(chains) - len(given[:len(chains)]))
        self.chains, self.skipped = chains, skipped
        self.xs = [chain_stmt(s, n) for s, n in zip(self.secrets, chains)]
        self.res["instances"] = {"k": k, "chains": len(chains), "n": sorted(set(chains)), "skipped": skipped,
                                 "tree": {"n": tree_n, "leaves": tree_leaves, "depth": depth},
                                 "secrets": "fresh, os.urandom, held by the runner only (S9I-m4)",
                                 "secrets_sha256": hashlib.sha256(b"".join(self.secrets)).hexdigest()}
        # the whole-evaluation cap, derived from the per-step caps (S9F-M5)
        self.derive_budget(runs)
        # 0. the native prover's build (untimed, sandboxed, budget prover_build_s)
        if cfg["prover_build"]:
            b = cfg["prover_build"]
            rc, wall, _ = R.run(b["cmd"], b["dir"], cfg["budgets"]["prover_build_s"], "prover build")
            if rc != 0:
                raise Reject(f"prover build failed (exit {rc})")
            self.res["prover_build_s"] = wall
        # 2. indexing (untimed)
        self.idx_budget, self.index_log, self.keys, self.layouts = cfg["budgets"]["index_total_s"], [], {}, {}
        for n in sorted(set(chains)):
            p = os.path.join(self.workdir, f"L_chain-{n}.layout.json")
            subprocess.run([sys.executable, "-I", cfg["gen"], "layout", "--n", str(n), p], check=True,
                           stdout=subprocess.DEVNULL)
            self.layouts[n] = p
            self.keys[n] = self.index(f"L_chain({n})", p)
        if self.tree_bs:
            try:
                # S9D-m4: with index_C = "certified" the recursion key is the index of the certified
                # `C` compiled into the index executable (one reader: render-layout.py's, the same
                # rendering as the challenge's `C`), not of a parse of the layout file
                self.keys["C"] = self.index("C_V", None if cfg["index_C"] == "certified" else cfg["layouts"]["C"])
                claim = cfg["claim"] or {}
                for what, mine in (("digestC", H(self.h, self.keys["C"]).hex()),
                                   ("digestL", H(self.h, self.keys[tree_n]).hex())):
                    if claim.get(what) != mine:
                        raise Reject(f"declared {what} {claim.get(what)!r} differs from the indexer's {mine} (S5-A13)")
            except Reject as e:
                self.fail(self.tree_bs, str(e))
        self.res["indexing"] = {"runs": self.index_log, "total_s": sum(r["wall_s"] for r in self.index_log),
                                "C": cfg["index_C"] if self.tree_bs else None}

    def derive_budget(self, runs):
        """S9F-M5: the whole-evaluation cap is the sum of the per-step caps over every process the
        evaluation may start (each run's leaves, steps, root and canaries; indexing; the prover
        build; the DoS tapes) plus `overhead_s` and `per_process_s` per process, so an entry that
        keeps every per-step cap is never rejected by the whole-evaluation cap."""
        b, tree = self.cfg["budgets"], bool(self.tree_bs)
        steps = self.tree_leaves - 1 if tree else 0
        kinds = {"leaf": len(self.chains), "wrap": self.tree_leaves // 2 if tree else 0,
                 "node": max(steps - self.tree_leaves // 2, 0), "root": 1 if tree else 0}
        canary_runs = sum(4 * min(self.cfg["canaries"]["per_kind"], c) for c in kinds.values())
        per_run = {"leaf_s": len(self.chains) * (b["leaf_s"] + b["verify_s"]),
                   "step_s": steps * (b["step_s"] + b["verify_s"]),
                   "root_s": b["root_s"] if tree else 0, "canary_s": canary_runs * b["verify_s"]}
        procs = runs * (len(self.chains) * 2 + steps * 2 + kinds["root"] + canary_runs) + \
            len(set(self.chains)) + (1 if tree else 0) + self.cfg["dos"]["tapes"] + bool(self.cfg["prover_build"])
        parts = {"runs": runs, "per_run": per_run, "index_total_s": b["index_total_s"],
                 "prover_build_s": b["prover_build_s"] if self.cfg["prover_build"] else 0,
                 "dos_s": self.cfg["dos"]["tapes"] * b["verify_s"], "overhead_s": b["overhead_s"],
                 "processes": procs, "per_process_s": b["per_process_s"]}
        total = (runs * sum(per_run.values()) + parts["index_total_s"] + parts["prover_build_s"]
                 + parts["dos_s"] + b["overhead_s"] + procs * b["per_process_s"])
        self.R.eval_cap = total
        self.res["budget"] = {"eval_s": total, "derived_from": parts}

    def index(self, name, layout_path):
        """The compiled `index` on a layout file, or (`layout_path` None) on the certified `C`."""
        d = self.R.stage(f"index-{name}", {}, layout_path)
        args = ["layout.json", "vkc.bin"] if layout_path else ["--certified-C", "vkc.bin"]
        rc, wall, rss = self.R.run(self.cfg["index"] + args, d, max(self.idx_budget, 0.001), f"index {name}")
        self.idx_budget -= wall
        if rc != 0 or not os.path.exists(os.path.join(d, "vkc.bin")):
            raise Reject(f"index {name}: failed (exit {rc})")
        vkc = open(os.path.join(d, "vkc.bin"), "rb").read()
        printed = open(os.path.join(d, ".stdout")).read().strip()
        if printed != H(self.h, vkc).hex():
            raise Reject(f"index {name}: printed digest {printed!r} is not the hash of its key bytes")
        self.index_log.append({"layout": name, "source": "certified C" if layout_path is None else "layout file",
                               "wall_s": wall, "maxrss_kb": rss, "key_bytes": len(vkc), "digest": printed})
        self.R.cleanup(d)
        return vkc

    def canary(self, kind, vk, x, proof, other_vk, what):
        """S9I-m3: the verifier must reject the proof with a byte appended or removed (the tape
        grammar: every protocol), under a statement with one bit flipped (`y` of a leaf, `d2` of a
        node) and under the other key (leaf proofs under `vkC`, node proofs under `vkL`; when the
        two keys differ): by soundness. Untimed; the first `canaries.per_kind` proofs of each kind
        in each run. An accepted canary rejects the evaluation (the executable is wrong)."""
        if self.left.get(kind, 0) <= 0:
            return
        self.left[kind] -= 1
        x2 = list(x); x2[0 if kind == "leaf" else 8] ^= 1
        cases = [("one byte appended", vk, x, proof + b"\x00"), ("last byte removed", vk, x, proof[:-1]),
                 ("one statement bit flipped", vk, x2, proof)]
        if other_vk is not None and other_vk != vk:
            cases.append(("the other key", other_vk, x, proof))
        for name, k, xx, t in cases:
            rc, _, _ = self.R.run_verify("canary", k, xx, t, self.cfg["budgets"]["verify_s"], f"{what} canary")
            if rc == 0:
                raise Fatal(f"{what}: the verifier ACCEPTED a canary ({name}; S9I-m3)")
            if rc != 1:
                raise Fatal(f"{what}: the verifier crashed on a canary ({name}, exit {rc})")
            self.canaries += 1

    def run_once(self, rep):
        """One run (§6.3 steps 3-5): every leaf, then the tree and the root; returns its record."""
        cfg, R, caps = self.cfg, self.R, self.cfg["caps"]
        run = {"leaves": [], "wrap": [], "nodes": [], "root": None}
        self.left = {k: cfg["canaries"]["per_kind"] for k in ("leaf", "wrap", "node", "root")}
        proofs = []
        vkC = self.keys.get("C")
        for i, (s, n, x) in enumerate(zip(self.secrets, self.chains, self.xs)):
            tree_chain = i < self.tree_leaves
            if not tree_chain and "L" in self.failed:
                continue
            what = f"run {rep} leaf {i} (n = {n})"
            try:
                proof, pw, prss = R.prove(f"r{rep}-leaf{i}", LEAF, self.layouts[n],
                                          {"vkc.bin": self.keys[n], "stmt.bin": stmt_bytes(x), "secret.hex": s.hex() + "\n"},
                                          cfg["budgets"]["leaf_s"], what)
                if len(proof) > caps["tape_L"] and "L" in self.boards:
                    self.fail({"L"}, f"{what}: proof of {len(proof)} bytes above the board-L cap {caps['tape_L']} (S7-A3)")
                if not ((tree_chain and self.tree_bs) or "L" not in self.failed):
                    continue                                  # no board still needs this proof
                vw, vrss = R.verify(self.keys[n], x, proof, cfg["budgets"]["verify_s"], what, caps["tape_R"])
                self.canary("leaf", self.keys[n], x, proof, vkC, what)
            except Reject as e:
                if tree_chain or isinstance(e, Fatal):
                    raise                                     # every board uses the tree chains
                self.fail({"L"}, str(e))
                continue
            run["leaves"].append({"chain": i, "n": n, **step_record(pw, prss, vw, vrss, proof)})
            proofs.append(proof)
        if self.tree_bs and not (self.tree_bs <= set(self.failed)):
            try:
                self.tree(self.xs[:self.tree_leaves], proofs[:self.tree_leaves], rep, run)
            except Reject as e:
                if isinstance(e, Fatal):
                    raise
                self.fail(self.tree_bs, str(e))
        scores = lambda rs: median([r["score_s"] for r in rs])
        run["S_leaf"] = scores(run["leaves"])
        run["S_leaf_by_n"] = {str(n): scores([r for r in run["leaves"] if r["n"] == n]) for n in sorted(set(self.chains))}
        run["S_wrap"] = scores(run["wrap"])
        run["S_by_level"] = {str(lv): scores([r for r in run["nodes"] if r["level"] == lv])
                             for lv in sorted({r["level"] for r in run["nodes"]})}
        groups = {}
        for r in run["nodes"]:
            groups.setdefault(level_group(r["level"]), []).append(r["score_s"])
        run["S_rec_groups"] = {g: median(v) for g, v in sorted(groups.items())}
        run["S_rec"] = max(run["S_rec_groups"].values()) if groups else None
        self.runs.append(run)
        self.res["runs"] = self.runs
        self.log(f"run {rep}: S_rec {run['S_rec']} (groups {run['S_rec_groups']}), S_wrap {run['S_wrap']}, "
                 f"S_leaf {run['S_leaf']} ({time.perf_counter() - R.t0:.1f} s elapsed)")
        return run

    def tree(self, xs, proofs, rep, run):
        """§6.3 steps 4-5: the wrap steps, the node steps level by level, the root check."""
        cfg, R, caps, h = self.cfg, self.R, self.cfg["caps"], self.h
        vkC, vkL = self.keys["C"], self.keys[self.tree_n]
        dC, dL = H(h, vkC), H(h, vkL)
        level = [(LEAF, x, p) for x, p in zip(xs, proofs)]
        lv = 1
        while len(level) > 1:
            nxt = []
            for j in range(0, len(level), 2):
                (t1, x1, p1), (t2, x2, p2) = level[j], level[j + 1]
                x = node_stmt(h, dC, dL, t1, t2, x1, x2)
                what = f"run {rep} level {lv} step {j // 2}"
                files = {"vkc.bin": vkC, "vkC.bin": vkC, "vkL.bin": vkL, "stmt.bin": stmt_bytes(x),
                         "child1.stmt": stmt_bytes(x1), "child1.proof": p1, "child1.tag": t1 + "\n",
                         "child2.stmt": stmt_bytes(x2), "child2.proof": p2, "child2.tag": t2 + "\n"}
                proof, pw, prss = R.prove(f"r{rep}-l{lv}-s{j // 2}", NODE, cfg["layouts"]["C"], files,
                                          cfg["budgets"]["step_s"], what)
                vw, vrss = R.verify(vkC, x, proof, cfg["budgets"]["verify_s"], what, caps["tape_R"])
                self.canary("wrap" if lv == 1 else "node", vkC, x, proof, vkL, what)
                (run["wrap"] if lv == 1 else run["nodes"]).append(
                    {"level": lv, "step": j // 2, "tags": [t1, t2], **step_record(pw, prss, vw, vrss, proof)})
                nxt.append((NODE, x, proof))
            level, lv = nxt, lv + 1
        (_, xr, pr), = level
        if tree_root(h, dC, dL, self.depth, xs) != xr:
            raise Reject(f"run {rep}: the root statement is not treeRoot of the leaf statements (rootOK)")
        vw, vrss = R.verify(vkC, xr, pr, cfg["budgets"]["root_s"], f"run {rep} root", caps["tape_R"])
        self.canary("root", vkC, xr, pr, vkL, f"run {rep} root")
        run["root"] = {"verify_s": vw, "verify_maxrss_kb": vrss, "proof_bytes": len(pr), "stmt": stmt_bytes(xr).hex()}

    def finish(self):
        """§6.3 step 6 (per-board verdicts and scores: medians of per-run medians) and 7 (DoS)."""
        cfg, runs, out = self.cfg, self.runs, {}
        med = lambda key: median([r[key] for r in runs if r[key] is not None])
        if "L" in self.boards:
            out["L"] = {"ranked": False,
                        "note": "published, unranked (S9I-M1): a leaf's witness is its 32-byte start, so no "
                                "proof-size cap separates sending it from a SNARK",
                        "S_leaf": med("S_leaf"),
                        "S_leaf_by_n": {n: median([r["S_leaf_by_n"][n] for r in runs if r["S_leaf_by_n"].get(n) is not None])
                                        for n in runs[0]["S_leaf_by_n"]} if runs else {},
                        "skipped": self.skipped, "proof_cap": cfg["caps"]["tape_L"],
                        "max_proof_bytes": max((l["proof_bytes"] for r in runs for l in r["leaves"]), default=None)}
        if self.tree_bs:
            by_group = {}
            for r in runs:
                for g, v in r["S_rec_groups"].items():
                    if v is not None:
                        by_group.setdefault(g, []).append(v)
            by_group = {g: median(v) for g, v in sorted(by_group.items())}
            by_level = {}
            for r in runs:
                for lv, v in r["S_by_level"].items():
                    by_level.setdefault(lv, []).append(v)
            out["R"] = {"ranked": True,
                        "S_rec": max(by_group.values()) if by_group else None,
                        "S_rec_by_group": by_group,
                        "statistic": "max over the level groups 2, 3, 4+ of the median over runs of the "
                                     "per-run median step time (S9I-M2)",
                        "S_by_level": {lv: median(v) for lv, v in sorted(by_level.items(), key=lambda kv: int(kv[0]))},
                        "steps_per_run": len(runs[0]["nodes"]) if runs else 0}
            out["W"] = {"ranked": False, "S_wrap": med("S_wrap"), "steps_per_run": len(runs[0]["wrap"]) if runs else 0}
        for b, v in out.items():
            v["verdict"], v["reason"] = ("REJECT", self.failed[b]) if b in self.failed else ("ACCEPT", None)
        # 7. DoS column (unranked): random tapes under the leaf key (first statement) and, with the
        # tree, under the recursion key (a level-1 statement), alternately (S9I-m3)
        dos = cfg["dos"]
        if dos["tapes"]:
            rng = random.Random(dos["seed"]) if dos["seed"] is not None else random.SystemRandom()
            targets = [("leaf key", self.keys[self.tree_n], self.xs[0])]
            if self.tree_bs and "C" in self.keys:
                dC, dL = H(self.h, self.keys["C"]), H(self.h, self.keys[self.tree_n])
                targets.append(("recursion key", self.keys["C"],
                                node_stmt(self.h, dC, dL, LEAF, LEAF, self.xs[0], self.xs[1])))
            worst, accepted, per = 0.0, 0, {t[0]: 0 for t in targets}
            for i in range(dos["tapes"]):
                name, k, x = targets[i % len(targets)]
                t = rng.randbytes(rng.randrange(dos["max_len"] + 1))
                rc, wall, _ = self.R.run_verify("dos", k, x, t, cfg["budgets"]["verify_s"], f"DoS tape {i}")
                if rc not in (0, 1):
                    raise Reject(f"DoS tape {i} ({name}): verify crashed (exit {rc})")
                accepted += rc == 0
                per[name] += 1
                worst = max(worst, wall)
            out["DoS"] = {"tapes": dos["tapes"], "by_key": per, "max_verify_s": worst, "accepted": accepted}
            if accepted:
                raise Reject(f"DoS: {accepted} random tapes were accepted")
        out["canaries"] = {"verify_runs": self.canaries, "per_kind_per_run": cfg["canaries"]["per_kind"],
                           "rejected": self.canaries}
        self.res["scores"] = out
        if "R" in out:
            self.res["ranked"] = {"board": "R", "S_rec": out["R"]["S_rec"], "verdict": out["R"]["verdict"]}


def machine_info():
    info = {"hostname": platform.node(), "kernel": platform.release(), "machine": platform.machine(),
            "python": platform.python_version(), "cpus": os.cpu_count()}
    try:
        for line in open("/proc/cpuinfo"):
            if line.startswith("model name"):
                info["cpu"] = line.split(":", 1)[1].strip(); break
        for line in open("/proc/cpuinfo"):
            if line.startswith("flags"):
                info["has_clmul"] = " pclmulqdq " in f" {line.split(':', 1)[1]} "; break
        for line in open("/proc/meminfo"):
            if line.startswith("MemTotal"):
                info["mem_kb"] = int(line.split()[1]); break
    except OSError:
        pass
    info["glibc"] = " ".join(platform.libc_ver())
    return info


def sha256_path(p):
    """sha256 of a file, or of a directory tree (relative paths and file hashes, sorted)."""
    if os.path.isdir(p):
        h = hashlib.sha256()
        for d, dns, fns in os.walk(p):
            dns.sort()
            for f in sorted(fns):
                q = os.path.join(d, f)
                h.update(os.path.relpath(q, p).encode() + b"\0" + sha256_path(q).encode() + b"\n")
        return h.hexdigest()
    with open(p, "rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


# the per-entry configuration keys; the rest is the season's bench configuration (S9I-m5)
ENTRY_KEYS = {"verify", "index", "prover", "gen", "layouts", "claim", "k", "keep", "sandbox", "sandbox_ro",
              "prover_build", "index_C", "boards", "cfg", "submitter", "hardware_id"}

def canon(v):
    return json.dumps(v, sort_keys=True, separators=(",", ":"))

def identity(cfg):
    """What a result was measured under (S9I-m5): the season's configuration (its sha256), the
    hardware id, and the entry: the executables' hashes, the prover's argv and the hashes of the
    files it names, the claim (digests) and the recursion layout's hash; `entry_id` is the sha256 of
    the entry part."""
    season = {k: v for k, v in cfg.items() if k not in ENTRY_KEYS}
    season["dos"] = {k: v for k, v in season["dos"].items() if k != "seed"}
    exe = lambda a: os.path.realpath(shutil.which(a) or a)
    prover = {}
    for i, a in enumerate(cfg["prover"]):
        q = exe(a) if i == 0 else a
        if os.path.exists(q):
            prover[a] = sha256_path(q)
    entry = {"verify_sha256": sha256_path(exe(cfg["verify"][0])), "index_sha256": sha256_path(exe(cfg["index"][0])),
             "prover_argv": cfg["prover"], "prover_sha256": prover, "prover_build_sha256": sha256_path(cfg["prover_build"]["dir"]) if cfg["prover_build"] else None,
             "claim": cfg["claim"], "cfg": cfg["cfg"], "k": cfg["k"],
             "layout_C_sha256": sha256_path(cfg["layouts"]["C"]) if (cfg.get("layouts") or {}).get("C") else None}
    return {"config_sha256": hashlib.sha256(canon(season).encode()).hexdigest(),
            "hardware_id": cfg.get("hardware_id") or "unset (harness/reference-machine.md §1)",
            "submitter": cfg.get("submitter"),
            "entry": entry, "entry_id": hashlib.sha256(canon(entry).encode()).hexdigest()}


def load_config(path):
    cfg = json.load(open(path))
    out = json.loads(json.dumps(DEFAULTS))
    for k, v in cfg.items():
        if k not in DEFAULTS and k not in ("verify", "index", "prover", "gen", "layouts", "keep", "k"):
            raise SystemExit(f"run-benchmark: unknown config key {k!r}")
        if k == "cfg" and set(v) - {"hash"}:
            raise SystemExit(f"run-benchmark: cfg takes only \"hash\" (the arity is the submission's, S6b-m5)")
        if k == "budgets" and "eval_s" in v:
            raise SystemExit("run-benchmark: budgets.eval_s is derived from the per-step caps (S9F-M5), not set")
        if k == "index_C" and v not in ("certified", "json"):
            raise SystemExit("run-benchmark: index_C is \"certified\" or \"json\"")
        if isinstance(v, dict) and isinstance(out.get(k), dict) and k not in ("leafboard", "classes"):
            out[k].update(v)
        else:
            out[k] = v
    for k in ("verify", "index", "prover", "gen", "k"):
        if k not in out:
            raise SystemExit(f"run-benchmark: config needs {k!r}")
    for k in ("verify", "index", "prover"):
        if isinstance(out[k], str):
            out[k] = [out[k]]
    if "R" in out["boards"] and not (out.get("layouts") or {}).get("C"):
        raise SystemExit("run-benchmark: board R needs layouts.C (the submitted C_V JSON)")
    return out


def preflight(cfg):
    """`run` fails closed (S6b-M1, S6b-m1): no evaluation without the sandbox and the cgroup."""
    sb = cfg.get("sandbox")
    if not sb or not (os.path.isfile(sb) and os.access(sb, os.X_OK)):
        return (f"no sandbox: the config's \"sandbox\" must name scripts/bwrap-landrun.sh (got {sb!r}); "
                "the runner does not run unsandboxed steps (S6b-M1)")
    try:
        ok = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", "MemoryMax=64M",
                             "-p", "OOMPolicy=continue", "--", "true"],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=30).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        ok = False
    if not ok:
        return ("no memory cgroup: `systemd-run --user --scope -p MemoryMax=… -p OOMPolicy=continue` is unavailable; the runner "
                "caps every step's whole process tree through a cgroup and does not fall back to "
                "per-process accounting (S6b-m1, harness/reference-machine.md)")
    return None


def new_result(cfg, workdir, kind="bench-result/2"):
    return {"schema": f"recursion.fast/{kind}", "verdict": None, "reason": None,
            "started": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "machine": machine_info(), **identity(cfg),
            "config": {k: v for k, v in cfg.items() if k != "claim"}, "claim": cfg["claim"], "workdir": workdir}


def cmd_run(a):
    cfg = load_config(a.config)
    cfg["keep"] = a.keep or cfg.get("keep", False)
    base = a.workdir or tempfile.mkdtemp(prefix="rf-bench-")
    os.makedirs(base, exist_ok=True)
    workdir = os.path.realpath(tempfile.mkdtemp(prefix="eval-", dir=base))
    res = new_result(cfg, workdir)
    log = lambda m: print(f"run-benchmark: {m}", flush=True)
    t0 = time.perf_counter()
    try:
        bad = preflight(cfg)
        if bad:
            raise Reject(bad)
        E = Evaluation(cfg, workdir, res, log)
        E.prepare(cfg["repeats"])
        for rep in range(cfg["repeats"]):
            if all(b in E.failed for b in E.boards):
                break
            E.run_once(rep)
        E.finish()
        boards = {b: v for b, v in res["scores"].items() if "verdict" in v}
        ok = [b for b, v in boards.items() if v["verdict"] == "ACCEPT"]
        res["verdict"] = "ACCEPT" if ok else "REJECT"
        res["accepted_boards"] = ok
        if not ok:
            res["reason"] = "; ".join(f"board {b}: {v['reason']}" for b, v in boards.items())
    except Reject as e:
        res["verdict"], res["reason"] = "REJECT", str(e)
    res["elapsed_s"] = time.perf_counter() - t0
    with open(a.out, "w") as f:
        json.dump(res, f, indent=1)
    if not cfg["keep"]:
        shutil.rmtree(workdir, ignore_errors=True)
    log(f"{res['verdict']}" + (f" ({res['reason']})" if res["reason"] else "") + f" in {res['elapsed_s']:.1f} s; {a.out}")
    for b, sc in (res.get("scores") or {}).items():
        log(f"board {b}: {sc}")
    return 0 if res["verdict"] == "ACCEPT" else 1


def is_record(new, standing, margin=0.03):
    """The screening rule (DESIGN §6.4): a score (lower is better) is a TENTATIVE record iff there
    is no standing record or it beats the standing one by at least `margin` (relative):
    `new <= (1 - margin) * standing`. A tentative record is confirmed only by `compare` (S9I-M3)."""
    if not (0 <= margin < 1):
        raise ValueError("margin must be in [0, 1)")
    return standing is None or new <= (1 - margin) * standing


def comparable(r1, r2):
    """Two results may be compared iff they ran the season's configuration on the same hardware."""
    for k in ("config_sha256", "hardware_id"):
        if r1.get(k) != r2.get(k):
            return f"the results differ in {k} ({r1.get(k)} vs {r2.get(k)}): not comparable (S9I-m5)"
    return None


def cmd_record(a):
    new, std = json.load(open(a.new)), json.load(open(a.standing))
    why = comparable(new, std)
    if why is None and new.get("entry_id") == std.get("entry_id"):
        why = "the same entry (entry_id): a resubmission replaces, it does not set a record"
    if why is None and (new.get("ranked") or {}).get("verdict") != "ACCEPT":
        why = "the new result has no accepted ranked board (R)"
    if why:
        print(f"not comparable: {why}")
        return 2
    s_new, s_std = new["ranked"]["S_rec"], (std.get("ranked") or {}).get("S_rec")
    r = is_record(s_new, s_std, a.margin)
    print(f"{'TENTATIVE RECORD (confirm with `compare`: 5 interleaved pairs, one session)' if r else 'not a record'}: "
          f"S_rec {s_new} vs standing {s_std} (margin {a.margin:.1%})")
    return 0 if r else 1


def cmd_compare(a):
    """S9I-M3: the paired confirmation of a tentative record, or (`--calibrate`, one config) the
    calibration of the margin from self-pairs. Both entries are run in ONE session on ONE fresh set
    of tree instances, interleaved run by run in ABBA order (standing, challenger; challenger,
    standing; …, so that a drift or an order effect cancels), board R only;
    pair i's ratio is S_rec(challenger, run i) / S_rec(standing, run i), which cancels the
    session's drift. A record iff the median ratio <= 1 - margin. The result also gives sigma, the
    sd of the per-pair log ratio, and the pairs a margin m needs, ceil((3.75 sigma / m)^2) (the
    median's 3 sd below the margin; harness/reference-machine.md §4)."""
    cs = load_config(a.standing)
    cc = load_config(a.challenger or a.standing)
    log = lambda m: print(f"compare: {m}", flush=True)
    base = a.workdir or tempfile.mkdtemp(prefix="rf-compare-")
    os.makedirs(base, exist_ok=True)
    out = {"schema": "recursion.fast/compare-result/1", "pairs": [], "margin": a.margin, "verdict": None,
           "reason": None, "calibration": a.calibrate, "machine": machine_info(),
           "started": time.strftime("%Y-%m-%dT%H:%M:%S%z")}
    t0 = time.perf_counter()
    try:
        for c in (cs, cc):
            c["boards"], c["dos"]["tapes"] = ["R"], 0       # ranked board only; DoS is a property, not a speed
        ids = [identity(cs), identity(cc)]
        out["standing"], out["challenger"] = ids
        if ids[0]["config_sha256"] != ids[1]["config_sha256"] or ids[0]["hardware_id"] != ids[1]["hardware_id"]:
            raise Reject("the two configurations differ in the season's configuration or hardware id (S9I-m5)")
        if (ids[0]["entry_id"] == ids[1]["entry_id"]) != a.calibrate:
            raise Reject("--calibrate compares an entry with itself; a confirmation needs two different entries"
                         if not a.calibrate else "--calibrate takes one configuration")
        bad = preflight(cs) or preflight(cc)
        if bad:
            raise Reject(bad)
        secrets = fresh_secrets(cs["tree"]["leaves"])              # one fresh set, both entries
        res = [new_result(c, None, "compare-entry/1") for c in (cs, cc)]
        E = [Evaluation(c, os.path.realpath(tempfile.mkdtemp(prefix=f"{w}-", dir=base)), r, log, secrets)
             for c, r, w in zip((cs, cc), res, ("standing", "challenger"))]
        for e in E:
            e.prepare(a.pairs)
            if "R" in e.failed:
                raise Reject(f"{'standing' if e is E[0] else 'challenger'}: {e.failed['R']}")
        for i in range(a.pairs):
            if i % 2 == 0:                  # ABBA order: a drift or an order effect cancels in pairs
                rs = E[0].run_once(i); rc = E[1].run_once(i)
            else:
                rc = E[1].run_once(i); rs = E[0].run_once(i)
            for e, who in zip(E, ("standing", "challenger")):
                if "R" in e.failed:
                    raise Reject(f"{who}, pair {i}: {e.failed['R']}")
            out["pairs"].append({"standing_S_rec": rs["S_rec"], "challenger_S_rec": rc["S_rec"],
                                 "ratio": rc["S_rec"] / rs["S_rec"]})
            log(f"pair {i}: ratio {rc['S_rec'] / rs['S_rec']:.4f}")
        ratios = [p["ratio"] for p in out["pairs"]]
        out["median_ratio"] = median(ratios)
        if len(ratios) >= 2:
            sigma = statistics.stdev([math.log(r) for r in ratios])
            out["sigma_log_ratio"] = sigma
            out["pairs_needed_for_margin"] = max(1, math.ceil((3.75 * sigma / a.margin) ** 2))
        out["record"] = (not a.calibrate) and out["median_ratio"] <= 1 - a.margin
        out["verdict"] = "RECORD" if out["record"] else ("CALIBRATED" if a.calibrate else "NOT A RECORD")
    except Reject as e:
        out["verdict"], out["reason"] = "REJECT", str(e)
    out["elapsed_s"] = time.perf_counter() - t0
    with open(a.out, "w") as f:
        json.dump(out, f, indent=1)
    log(f"{out['verdict']}" + (f" ({out['reason']})" if out["reason"] else "")
        + (f": median ratio {out.get('median_ratio')}, sigma {out.get('sigma_log_ratio')}, "
           f"pairs needed {out.get('pairs_needed_for_margin')}" if not out["reason"] else "") + f"; {a.out}")
    return 0 if out["verdict"] in ("RECORD", "CALIBRATED") else 1


def cmd_selftest(a):
    """Cross-check the re-implemented statement functions against the kernel-checked values of
    Controls/RecursionData.lean (`xN`, `xR`, `xT`, `xNK`: `nodeStmt_kat`, `treeKat`, `rootOK_xT`,
    `nodeStmt_kat_keys`) and the chain statement against gen-chain-layout.py; the record rule, the
    level groups and the paired statistic."""
    src = open(a.lean_data).read()
    def lean_words(name):
        m = re.search(rf"def {name} : Stmt := stmtOfWords\s*\[([^\]]*)\]", src)
        return [int(w, 16) for w in re.findall(r"0x([0-9a-f]+)", m.group(1))]
    xN, xR, xT, xNK = lean_words("xN"), lean_words("xR"), lean_words("xT"), lean_words("xNK")
    # the key vkc2 of Controls/CompileToy.lean: VK = [0x1234], index root of [100], [101] at arity 2;
    # vkK of Controls/RecursionData.lean: VK = [0x1235], the same root
    leafh = lambda e: hashlib.blake2s(e.to_bytes(8, "little")).digest()
    root = hashlib.blake2s(leafh(100) + leafh(101)).digest()
    vkc2 = (0x1234).to_bytes(8, "little") + root
    vkK = (0x1235).to_bytes(8, "little") + root
    D, DK = H("blake2s", vkc2), H("blake2s", vkK)
    assert D.hex().startswith("0f4c678b"), D.hex()              # digest_kat
    x0 = [(i * 0x0101) % U64 for i in range(32)]
    x1 = list(x0); x1[31] ^= 1
    ok = []
    ok.append(("nodeStmt_kat (xN)", node_stmt("blake2s", D, D, LEAF, LEAF, x0, x1) == xN))
    ok.append(("nodeStmt_kat_keys (xNK: d0 = D vkC, d1 = D vkL, distinct keys; S9D-m2)",
               node_stmt("blake2s", D, DK, LEAF, LEAF, x0, x1) == xNK))
    ok.append(("a d0/d1 swap is caught", node_stmt("blake2s", DK, D, LEAF, LEAF, x0, x1) != xNK))
    ok.append(("xR (node, leaf)", node_stmt("blake2s", D, D, NODE, LEAF, xN, x0) == xR))
    ok.append(("treeKat (xT)", node_stmt("blake2s", D, D, NODE, NODE, xN, xN) == xT))
    ok.append(("rootOK_xT", tree_root("blake2s", D, D, 2, [x0, x1, x0, x1]) == xT))
    ok.append(("rootOK_leaf", tree_root("blake2s", D, D, 2, [x0, x1, x0, x1]) != x0))
    ok.append(("rootOK_odd", tree_root("blake2s", D, D, 2, [x0, x1, x0]) is None))
    ok.append(("depth mismatch", tree_root("blake2s", D, D, 1, [x0, x1, x0, x1]) is None))
    ok.append(("empty", tree_root("blake2s", D, D, 1, []) is None))
    if a.gen:
        with tempfile.TemporaryDirectory() as t:
            s = bytes(range(32))
            for n in (1, 4):
                subprocess.run([sys.executable, "-I", a.gen, "witness", "--n", str(n), "--secret-file", "-",
                                os.path.join(t, "w.json"), os.path.join(t, "x.json")],
                               input=(s.hex() + "\n").encode(), check=True, stdout=subprocess.DEVNULL)
                want = [int(v, 16) for v in json.load(open(os.path.join(t, "x.json")))["x"]]
                ok.append((f"chain statement n = {n} (gen-chain-layout.py)", chain_stmt(s, n) == want))
    ok.append(("record rule (screening)", is_record(97.0, 100.0) and not is_record(97.01, 100.0) and is_record(5.0, None)))
    ok.append(("level groups 2 | 3 | 4+", [level_group(l) for l in range(2, 7)] == ["2", "3", "4+", "4+", "4+"]))
    ok.append(("fresh secrets differ", len(set(fresh_secrets(64))) == 64))
    for name, good in ok:
        print(f"selftest: {name}: {'OK' if good else 'FAIL'}")
    return 0 if all(g for _, g in ok) else 1


