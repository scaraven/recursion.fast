#!/usr/bin/env python3
"""run-benchmark.py: the benchmark runner (DESIGN §6.3, §6.4; Stage 6b; S9 fix pass).

  python3 -I harness/run-benchmark.py run --config CONFIG.json --out RESULT.json [--workdir DIR] [--keep]
        exit 0 iff at least one requested board is accepted
  python3 -I harness/run-benchmark.py compare --standing CFG --challenger CFG [--pairs 5] [--margin 0.03]
        --out RESULT.json [--workdir DIR]     the paired confirmation of a tentative record (S9I-M3;
        one session, one fresh set of instances, interleaved ABBA, a record iff the median ratio <= 1 - margin)
  python3 -I harness/run-benchmark.py compare --calibrate --standing CFG --pairs 10 --out RESULT.json
        self-pairs of one entry: sigma and the pairs a margin needs (harness/reference-machine.md §4)
  python3 -I harness/run-benchmark.py record NEW.json STANDING.json [--margin 0.03]
        screening: exit 0 iff NEW is a tentative record against STANDING (same season config and
        hardware id, different entries)
  python3 -I harness/run-benchmark.py selftest --lean-data RecursionFast/Controls/RecursionData.lean
        [--gen harness/gen-chain-layout.py]

Boards (S9I-M1): **R is the only ranked board**; L (`S_leaf`) and W (`S_wrap`) are published,
unranked (`"ranked": false` in the result). A leaf's witness is its 32-byte start, so on board L no
proof-size cap separates "send the start and recompute the chain" from a SNARK.

One evaluation (`run`), §6.3:
 0. Class: the declared class `k` must admit `L_chain(tree.n)` (`classes`, S6-A1: 24 for 2^10),
    else the evaluation is rejected up front; a leaf-board size whose layout needs a larger class
    than `k` is skipped, not failed (2^12 needs 26; S7-M2).
 1. Instances: `tree.leaves` chains of length `tree.n` (the recursion tree; default 64 × 2^10) and,
    for board L, `leafboard` = {n: count} more (default 16 × 2^8 and, at k >= 26, 16 × 2^12). The
    secret starts are fresh for every evaluation, from the OS's randomness, held by this process
    only (S9I-m4: never read from a file); a secret reaches only its own leaf step's directory
    (every other sandbox hides the run directory). The statement of chain `(s, n)` is
    `x = (y0, y1, y2, y3, n, 0, ...)`, `y = blake2s256^n(s)` (S6-A3), computed here with hashlib.
 2. Indexing (untimed, budget `index_total_s`): the compiled `index` on `L_chain(n)` for every `n`
    (generated by harness/gen-chain-layout.py) and on `C_V`, each in its own sandbox. With
    `index_C = "certified"` (forced by scripts/harness.sh for board R, S9D-m4) `C_V`'s key is the
    index of the certified `C` compiled into the executable (`index --certified-C`), not of a
    parse of the layout file. Board R: the declared `digestC`, `digestL` must equal the indexer's
    digests of `C_V` and of `L_chain(tree.n)` (S5-A13); the indexer's keys, never the declared
    ones, are used below.
 3. Leaves: the native prover (`prover` + `leaf`) on every chain, budget `leaf_s`; every proof is
    verified (`verify`, budget `verify_s`) and must be accepted. Board L: every proof <= `tape_L`
    (2^17 bytes; S7-A3); board R: <= `tape_R` (2^20).
 4. Tree (board R): level 1 = `leaves/2` wrap steps (two leaf children), then node steps level by
    level up to the root (16 + 8 + 4 + 2 + 1 for 64 leaves). Each step: the prover (`node`) in a
    fresh directory with the children, keys and the aggregate statement `nodeStmt` (computed here,
    the contract's trusted definition re-implemented, cross-checked by `selftest` against the
    kernel-checked `treeKat`/`rootOK_xT`/`nodeStmt_kat_keys`), budget `step_s`; the output proof
    must verify under the recursion key.
 5. Root: the last statement must be `treeRoot cfg vkC vkL d xs` over the leaf statements
    (`rootOK`, S5-A12), and `NARG` on the root proof (budget `root_s`) must accept.
    Canaries (S9I-m3), untimed, for the first `canaries.per_kind` proofs of each kind (leaf, wrap,
    node, root) in each run: the verifier must REJECT the proof with one byte appended, with its
    last byte removed (the tape grammar: every protocol), under the statement with one bit flipped
    (`y` of a leaf, `d2` of a node) and under the other key (leaf proofs under `vkC`, node proofs
    under `vkL`, when they differ): by soundness. An accepted canary rejects the evaluation.
 6. Repeat `repeats` (3) times. `S_rec` (S9I-M2) is the slowest LEVEL GROUP: the max over the
    groups level 2, level 3 and levels >= 4 (pooled) of the median over runs of the per-run median
    step time; the per-level medians are published. (A median over all levels >= 2 is decided by
    level 2, whose children are the unranked wrap steps' proofs: wrap proofs that are expensive to
    prove and cheap to verify would make level 2 cheap and move the median without lowering the
    steady-state cost of a step.) `S_wrap`, `S_leaf` are medians of the per-run medians. Every
    failure (a proof that does not verify, a timeout, a crash, a missing output, a cap, memory
    above `mem_kb`, the whole evaluation above its derived cap) rejects: no partial credit. Boards
    are judged separately (S7-M2): a failure only board L depends on (a leaf-board chain, the 2^17
    cap) rejects board L; one only the tree depends on (`C_V`'s key, the digests, a step, the
    root) rejects boards R and W; anything else (a tree chain's leaf, indexing `L_chain`, a
    canary, the budget, the DoS column) rejects every board.
 7. DoS column (unranked): `verify` on `dos.tapes` random tapes, alternately under the leaf key
    (the first leaf statement) and the recursion key (a level-1 statement); max wall time.

Budgets (S9F-M5): the per-step caps `leaf_s`, `step_s`, `root_s`, `verify_s`, `index_total_s`,
`prover_build_s` are the policy; the whole-evaluation cap is DERIVED from them (every process the
evaluation may start at its cap, plus `overhead_s` and `per_process_s` per process; `budget` in the
result), so an entry that keeps every per-step cap is never rejected by the whole-evaluation cap.

Results (S9I-m5) carry `config_sha256` (the season's bench configuration: everything but the
entry's keys), `hardware_id` (config, harness/reference-machine.md §1), the machine, and the entry:
the sha256 of the `verify` and `index` executables, of the prover's files and build directory, the
claim's digests and the recursion layout's hash (`entry_id`). `record` and `compare` refuse results
or configurations whose season configuration or hardware id differ.

Measurement (§6.4): each timed process is started in a fresh working directory holding copies of
its inputs (local disk), in its own cgroup capped at `mem_kb` (`systemd-run --user --scope -p
MemoryMax=`, S6b-m1), through the sandbox (`sandbox`, scripts/bwrap-landrun.sh --minimal-root:
only /usr, /etc, a fresh /tmp, the executables' directories and `sandbox_ro` readable, the run
directory (with the other chains' secrets) hidden, only the step directory writable, no network, own PID namespace,
cleared environment; S6b-m3). `run` refuses to start without both (S6b-M1). Its wall time is the
sandboxed process's, from its start to its exit (`date +%s%N` in the cgroup's organiser shell), and
its peak memory the cgroup's `memory.peak` (the whole process tree). The scope's `OOMPolicy=continue`
keeps systemd from stopping the scope (SIGTERM to the organiser shell) when the kernel kills a process
at the cap; a step whose cgroup records an `oom_kill` is rejected. A step's score is prover +
verifier wall time. Results are JSON (`--out`), written also on REJECT with the reason.

The prover interface (harness/README.md): `PROVER... leaf|node` in the step directory.
  leaf: layout.json (L_chain(n)), vkc.bin (the leaf key bytes), stmt.bin (256 bytes), secret.hex
        (the chain's start `s`)  ->  proof.bin. The prover generates the witness tables from `s`
        itself, inside the timed region (they are a function of `s`, S6-A4; S6b-A9 decision).
  node: layout.json (C_V), vkc.bin (= vkC.bin, the recursion key), vkC.bin, vkL.bin, stmt.bin (the
        aggregate statement), child1.{stmt,proof,tag}, child2.{stmt,proof,tag} (tag: leaf|node)
        ->  proof.bin
The verifier interface: `VERIFY vkc.bin stmt.bin proof.bin`, exit 0 = accept, 1 = reject
(harness/README.md). The indexer: `INDEX LAYOUT.json VKC_OUT`, or `INDEX --certified-C VKC_OUT` for
the `C` compiled into it; it prints the key's digest.
"""
