#!/usr/bin/env python3
"""run-benchmark.py: the benchmark runner (DESIGN §6.3, §6.4; Stage 6b).

  python3 -I harness/run-benchmark.py run --config CONFIG.json --secrets SECRETS --out RESULT.json
        [--workdir DIR] [--keep]          exit 0 iff at least one requested board is accepted
  python3 -I harness/run-benchmark.py secrets COUNT OUT          fresh random starts (os.urandom), mode 0600
  python3 -I harness/run-benchmark.py selftest --lean-data RecursionFast/Controls/RecursionData.lean
        [--gen harness/gen-chain-layout.py]
  python3 -I harness/run-benchmark.py record NEW STANDING [--margin 0.03]

One evaluation (`run`), §6.3:
 0. Class: the declared class `k` must admit `L_chain(tree.n)` (`classes`, S6-A1: 24 for 2^10),
    else the evaluation is rejected up front; a leaf-board size whose layout needs a larger class
    than `k` is skipped, not failed (2^12 needs 26; S7-M2).
 1. Instances: `tree.leaves` chains of length `tree.n` (the recursion tree; default 64 × 2^10) and,
    for board L, `leafboard` = {n: count} more (default 16 × 2^8 and, at k >= 26, 16 × 2^12). The secret starts are
    read from SECRETS (one line of 64 hex digits per chain, in that order), never from argv; a
    secret is visible only in its own leaf step's directory (every other sandbox hides it).
    The statement of chain `(s, n)` is `x = (y0, y1, y2, y3, n, 0, ...)`, `y = blake2s256^n(s)`
    (S6-A3), computed here with hashlib.
 2. Indexing (untimed, budget `index_total_s`): the compiled `index` on `L_chain(n)` for every `n`
    (generated by harness/gen-chain-layout.py) and on the submitted `C_V`, each in its own sandbox.
    Board R: the declared `digestC`, `digestL` must equal the indexer's digests of `C_V` and of
    `L_chain(tree.n)` (S5-A13); the indexer's keys, never the declared ones, are used below.
 3. Leaves: the native prover (`prover` + `leaf`) on every chain, budget `leaf_s`; every proof is
    verified (`verify`, budget `verify_s`) and must be accepted. Board L: every proof <= `tape_L`
    (2^17 bytes; S7-A3); board R: <= `tape_R` (2^20).
 4. Tree (board R): level 1 = `leaves/2` wrap steps (two leaf children), then node steps level by
    level up to the root (16 + 8 + 4 + 2 + 1 for 64 leaves). Each step: the prover (`node`) in a
    fresh directory with the children, keys and the aggregate statement `nodeStmt` (computed here,
    the contract's trusted definition re-implemented, cross-checked by `selftest` against the
    kernel-checked `treeKat`/`rootOK_xT`), budget `step_s`; the output proof must verify under the
    recursion key.
 5. Root: the last statement must be `treeRoot cfg vkC vkL d xs` over the leaf statements
    (`rootOK`, S5-A12), and `NARG` on the root proof (budget `root_s`) must accept.
 6. Repeat `repeats` (3) times; S_rec, S_wrap, S_leaf are medians of the per-run medians. Every
    failure (a proof that does not verify, a timeout, a crash, a missing output, a cap, memory
    above `mem_kb`, the whole evaluation above `eval_s`) rejects: no partial credit. Boards are
    judged separately (S7-M2): a failure only board L depends on (a leaf-board chain, the 2^17
    cap) rejects board L; one only the tree depends on (`C_V`'s key, the digests, a step, the
    root) rejects boards R and W; anything else (a tree chain's leaf, indexing `L_chain`, the
    budget, the DoS column) rejects every board.
 7. DoS column (unranked): `verify` on `dos.tapes` random tapes, max wall time.

Measurement (§6.4): each timed process is started in a fresh working directory holding copies of
its inputs (local disk), in its own cgroup capped at `mem_kb` (`systemd-run --user --scope -p
MemoryMax=`, S6b-m1), through the sandbox (`sandbox`, scripts/bwrap-landrun.sh --minimal-root:
only /usr, /etc, a fresh /tmp, the executables' directories and `sandbox_ro` readable, the run
directory and the secrets hidden, only the step directory writable, no network, own PID namespace,
cleared environment; S6b-m3). `run` refuses to start without both (S6b-M1). Its wall time is the
sandboxed process's, from its start to its exit (`date +%s%N` in the cgroup's organiser shell), and
its peak memory the cgroup's `memory.peak` (the whole process tree). The scope's `OOMPolicy=continue`
keeps systemd from stopping the scope (SIGTERM to the organiser shell) when the kernel kills a process
at the cap; a step whose cgroup records an `oom_kill` is rejected. A step's score is prover +
verifier wall time. Results are JSON (`--out`), written also on REJECT with the reason.

The prover interface (harness/README.md): `PROVER... leaf|node` in the step directory.
  leaf: layout.json (L_chain(n)), vkc.bin (the leaf key bytes), stmt.bin (256 bytes), secret.hex
        (the chain's start `s`)  ->  proof.bin. The prover generates the witness tables from `s`
        itself, inside the timed region (they are a function of `s`, S6-A4; S6b-A9 decision).
  node: layout.json (C_V), vkc.bin (= vkC.bin, the recursion key), vkC.bin, vkL.bin, stmt.bin (the
        aggregate statement), child1.{stmt,proof,tag}, child2.{stmt,proof,tag} (tag: leaf|node)
        ->  proof.bin
The verifier interface: `VERIFY vkc.bin stmt.bin proof.bin`, exit 0 = accept (harness/README.md).
"""
import argparse, hashlib, json, os, platform, random, re, shutil, signal, statistics, struct
import subprocess, sys, tempfile, threading, time

U64 = 1 << 64
LEAF, NODE = "leaf", "node"
TAGK = {LEAF: 0, NODE: 1}
DEFAULTS = {
    "boards": ["L", "R"],
    "cfg": {"hash": "blake2s"},                # the arity is the submission's (S6b-m5)
    "tree": {"n": 1024, "leaves": 64},
    "leafboard": {"256": 16, "4096": 16},      # with tree.n = 2^10: n in {2^8, 2^10} at class 24;
                                               # 2^12 only if the declared k >= 26 (S6-A1, S7-M2)
    "classes": {"256": 24, "1024": 24, "2048": 25, "4096": 26},   # least class of L_chain(n) (S6-A1)
    "repeats": 3,
    "budgets": {"index_total_s": 3600, "leaf_s": 120, "step_s": 600, "root_s": 60, "verify_s": 60,
                "eval_s": 6 * 3600, "mem_kb": 48 * 10 ** 6, "prover_build_s": 3600},
    "caps": {"tape_R": 2 ** 20, "tape_L": 2 ** 17},
    "dos": {"tapes": 1000, "max_len": 2 ** 20, "seed": None},
    "sandbox": None,           # REQUIRED by `run` (S6b-M1): scripts/bwrap-landrun.sh
    "sandbox_ro": [],          # extra read-only paths for the steps (the prover's build, …; S6b-m3)
    "claim": None,
    "prover_build": None,
}


class Reject(Exception):
    """A failure: the evaluation is rejected (DESIGN §6.3)."""


# ---- the contract's statement functions (Contract/Recursion.lean), re-implemented -------------

def H(cfg_hash, b):
    """`cfg.hash.run` (Contract/Compile.lean `HashId.run`): the menu has BLAKE2s-256 only."""
    if cfg_hash != "blake2s":
        raise Reject(f"hash {cfg_hash!r} is not on the menu")
    return hashlib.blake2s(bytes(b)).digest()

def stmt_bytes(x):
    """`stmtBytes`: the 32 elements, 8 bytes little-endian each."""
    return b"".join((v % U64).to_bytes(8, "little") for v in x)

def stmt_of_bytes(b):
    assert len(b) == 256
    return list(struct.unpack("<32Q", b))

def digest_to_slot(d):
    """`digestToSlot`: limb j = digest bytes 8j .. 8j+7, little-endian."""
    return list(struct.unpack("<4Q", d))

def node_stmt(h, dC, dL, t1, t2, x1, x2):
    """`nodeStmt cfg vkC vkL t1 t2 x1 x2` with `dC = D vkC`, `dL = D vkL`: d0 = dC, d1 = dL,
    d2 = H(x1 || x2), d3 = (tag t1, tag t2, 0, 0), d4 .. d7 = 0 (S5-A8, S5-A11)."""
    return (digest_to_slot(dC) + digest_to_slot(dL) + digest_to_slot(H(h, stmt_bytes(x1) + stmt_bytes(x2)))
            + [TAGK[t1], TAGK[t2], 0, 0] + [0] * 16)

def pair_up(h, dC, dL, t, xs):
    """`pairUp`: adjacent statements aggregated in order, all tagged `t`; None on an odd count."""
    if len(xs) % 2:
        return None
    return [node_stmt(h, dC, dL, t, t, xs[i], xs[i + 1]) for i in range(0, len(xs), 2)]

def tree_root(h, dC, dL, d, xs):
    """`treeRoot cfg vkC vkL d xs`: level 1 over leaves, above over nodes; None unless 2^d leaves."""
    t = LEAF
    for _ in range(d):
        xs = pair_up(h, dC, dL, t, xs)
        if xs is None:
            return None
        t = NODE
    return xs[0] if len(xs) == 1 else None

def chain_stmt(secret, n):
    """The statement of `R_chain(y, n; s)`: (y0, y1, y2, y3, n, 0, ...), y = blake2s256^n(s) (S6-A3)."""
    y = secret
    for _ in range(n):
        y = hashlib.blake2s(y).digest()
    return digest_to_slot(y) + [n] + [0] * 27


# ---- processes -------------------------------------------------------------------------------

class Runner:
    def __init__(self, cfg, workdir, secrets_path, log):
        self.cfg, self.workdir, self.log = cfg, workdir, log
        # hidden from every sandboxed process: the run directory (other steps, witnesses, layouts)
        # and the secrets file (bwrap-landrun.sh --hide)
        self.hidden = [workdir, secrets_path]
        for exe in (cfg["verify"][0], cfg["index"][0], cfg["prover"][0]):
            path = os.path.realpath(shutil.which(exe) or exe)
            if path.startswith(workdir + os.sep):
                raise Reject(f"{exe} lies inside the hidden run directory")
        # S6b-m3: a step sees only /usr, /etc, a fresh /tmp (bwrap-landrun.sh --minimal-root), its
        # own directory, and read-only: the executables' directories, the files the prover's argv
        # names, and `sandbox_ro`
        ro = set()
        for argv in (cfg["verify"], cfg["index"], cfg["prover"]):
            for a in argv:
                q = shutil.which(a) if os.sep not in a else a
                if q and os.path.exists(q):
                    ro.add(os.path.dirname(os.path.realpath(q)))
        self.ro = sorted(r for r in ro | set(cfg.get("sandbox_ro") or []) if not r.startswith(("/usr", "/etc")))
        for r in self.ro:      # (a parent of the run directory is fine: the hides come after the binds)
            if r == workdir or r.startswith(workdir + os.sep):
                raise Reject(f"read-only path {r} lies inside the hidden run directory")
        # S6b-m1: every sandboxed step runs in its own cgroup with the memory cap (systemd-run)
        mem = cfg["budgets"]["mem_kb"] * 1024
        self.cgroup = ["systemd-run", "--user", "--scope", "-q", "-p", f"MemoryMax={mem}",
                       "-p", "MemorySwapMax=0", "-p", "OOMPolicy=continue", "--"]
        self.t0 = time.perf_counter()
        self.counter = 0

    def fresh(self, name):
        """A fresh step directory (never reused)."""
        self.counter += 1
        d = os.path.join(self.workdir, f"{self.counter:05d}-{name}")
        os.mkdir(d, 0o700)
        return d

    def check_eval_budget(self):
        if time.perf_counter() - self.t0 > self.cfg["budgets"]["eval_s"]:
            raise Reject(f"the evaluation exceeded its budget of {self.cfg['budgets']['eval_s']} s")

    def run(self, argv, cwd, budget, what):
        """Run `argv` in `cwd`; return (exit code, wall s, peak KB). With a sandbox (always, under
        `run`, S6b-M1) the process runs in its own cgroup with `MemoryMax` = the cap (S6b-m1), inside
        `bwrap-landrun.sh --minimal-root` (S6b-m3); a small organiser shell in the cgroup, outside
        the sandbox, records the wall time of the sandboxed process (`date +%s%N` around it) and the
        cgroup's `memory.peak` (the whole process tree) and `oom_kill` count (`memory.events`) into a
        directory the sandbox does not see. `OOMPolicy=continue`: with systemd's default (`stop`) an
        OOM kill stops the whole scope, organiser shell included, and nothing is recorded.
        Without a sandbox (`measure-noise.py` only) the wall time is the spawn-to-exit time and the
        peak `os.wait4`'s `ru_maxrss` of the direct child."""
        self.check_eval_budget()
        sb = self.cfg["sandbox"]
        meta = None
        env = None
        if sb:
            meta = cwd + ".meta"                      # beside the step: hidden with the run directory
            os.mkdir(meta, 0o700)
            pre = [sb, "--minimal-root"]
            for r in self.ro:
                pre += ["--ro", r]
            for h in self.hidden:
                pre += ["--hide", h]
            pre += ["--env", "PATH", "--rwx", cwd, "--"]
            script = ('t0=$(date +%s%N); "$@"; rc=$?; t1=$(date +%s%N); '
                      'cg=$(cut -d: -f3 /proc/self/cgroup); '
                      'cat "/sys/fs/cgroup$cg/memory.peak" > "$RF_META/peak" 2>/dev/null; '
                      'sed -n "s/^oom_kill //p" "/sys/fs/cgroup$cg/memory.events" > "$RF_META/oom" 2>/dev/null; '
                      'echo $((t1 - t0)) > "$RF_META/wall"; exit $rc')
            argv = self.cgroup + ["sh", "-c", script, "rf-step"] + pre + list(argv)
            env = dict(os.environ, RF_META=meta)
        out = open(os.path.join(cwd, ".stdout"), "wb")
        err = open(os.path.join(cwd, ".stderr"), "wb")
        fired = []
        start = time.perf_counter_ns()
        p = subprocess.Popen(argv, cwd=cwd, stdin=subprocess.DEVNULL, stdout=out, stderr=err,
                             start_new_session=True, env=env)
        def kill():
            fired.append(True)
            try:
                os.killpg(p.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        timer = threading.Timer(budget, kill)
        timer.start()
        _, status, ru = os.wait4(p.pid, 0)       # blocking: the end of the timed region is exact
        wall = (time.perf_counter_ns() - start) / 1e9
        timer.cancel()
        p.returncode = os.waitstatus_to_exitcode(status)
        out.close(); err.close()
        if fired:
            raise Reject(f"{what}: timeout after {budget} s")
        cap = self.cfg["budgets"]["mem_kb"]
        peak = ru.ru_maxrss
        if meta:
            try:
                wall = int(open(os.path.join(meta, "wall")).read()) / 1e9
                peak = int(open(os.path.join(meta, "peak")).read()) // 1024
                oom = int(open(os.path.join(meta, "oom")).read())
            except (OSError, ValueError):
                raise Reject(f"{what}: no measurement from the step's cgroup (exit {p.returncode})")
            shutil.rmtree(meta, ignore_errors=True)
            if oom:       # any process of the step killed by the kernel at MemoryMax, exit code aside
                raise Reject(f"{what}: killed at the memory cap of {cap} KB (cgroup MemoryMax, "
                             f"{oom} oom_kill, exit {p.returncode})")
        if peak > cap:
            raise Reject(f"{what}: peak memory {peak} KB above {cap} KB")
        return p.returncode, wall, peak

    def stage(self, name, files, layout=None):
        """A fresh step directory with `files` ({name: bytes or str}) and `layout` as layout.json."""
        d = self.fresh(name)
        if layout:
            shutil.copyfile(layout, os.path.join(d, "layout.json"))
        for f, data in files.items():
            write(d, f, data)
        return d

    def prove(self, name, mode, layout, files, budget, what):
        """The prover (`prover` + `mode`) in a fresh step directory: (proof bytes, wall s, maxrss KB)."""
        d = self.stage(name, files, layout)
        rc, wall, rss = self.run(self.cfg["prover"] + [mode], d, budget, what)
        if rc != 0 or not os.path.isfile(os.path.join(d, "proof.bin")):
            raise Reject(f"{what}: the prover failed (exit {rc}) or wrote no proof.bin")
        proof = open(os.path.join(d, "proof.bin"), "rb").read()
        self.cleanup(d)
        return proof, wall, rss

    def run_verify(self, name, vkc, x, tape, budget, what):
        """`VERIFY vkc.bin stmt.bin proof.bin` in a fresh step directory: (exit code, wall s, maxrss KB)."""
        d = self.stage(name, {"vkc.bin": vkc, "stmt.bin": stmt_bytes(x), "proof.bin": tape})
        rc, wall, rss = self.run(self.cfg["verify"] + ["vkc.bin", "stmt.bin", "proof.bin"], d, budget, what)
        self.cleanup(d)
        return rc, wall, rss

    def verify(self, vkc, x, proof, budget, what, cap=None):
        """`NARG` on (key bytes, statement, tape) in a fresh directory; must accept."""
        if cap is not None and len(proof) > cap:
            raise Reject(f"{what}: proof of {len(proof)} bytes above the cap {cap}")
        rc, wall, rss = self.run_verify("verify", vkc, x, proof, budget, what)
        if rc != 0:
            raise Reject(f"{what}: the proof does not verify (exit {rc})")
        return wall, rss

    def cleanup(self, d):
        if not self.cfg.get("keep"):
            shutil.rmtree(d, ignore_errors=True)


def write(d, name, data):
    with open(os.path.join(d, name), "wb" if isinstance(data, bytes) else "w") as f:
        f.write(data)

def median(xs):
    return statistics.median(xs) if xs else None

def step_record(pw, prss, vw, vrss, proof):
    """A step's measurements; its score is prover + verifier wall time (§6.4)."""
    return {"prove_s": pw, "verify_s": vw, "score_s": pw + vw, "proof_bytes": len(proof),
            "prove_maxrss_kb": prss, "verify_maxrss_kb": vrss}


# ---- the evaluation --------------------------------------------------------------------------

def evaluate(cfg, secrets_path, workdir, res, log):
    """One evaluation. A failure shared by every board (instances, indexing of the leaf layouts,
    a tree chain's leaf, the evaluation budget, the DoS column) raises `Reject`; a failure of one
    board (board L: a leaf-board chain, the 2^17-byte cap; boards R and W: `C_V`'s key, the claimed
    digests, a tree step, the root) marks that board REJECT and the others go on (S7-M2)."""
    R = Runner(cfg, workdir, secrets_path, log)
    h = cfg["cfg"]["hash"]
    boards = set(cfg["boards"])
    failed = {}                                      # board -> reason
    def fail(bs, reason):
        for b in bs:
            if b in boards and b not in failed:
                failed[b] = reason
                log(f"board {b}: REJECT ({reason})")
    if "R" in boards:
        boards.add("W")                              # the wrap steps are part of the tree
    tree_bs = {"R", "W"} if "R" in boards else set()
    tree_n, tree_leaves = cfg["tree"]["n"], cfg["tree"]["leaves"]
    depth = tree_leaves.bit_length() - 1
    if tree_leaves != 2 ** depth or depth < 1:
        raise Reject(f"tree.leaves = {tree_leaves} is not a power of two >= 2")
    # classes (S6-A1, S7-M2): the declared class must admit L_chain(tree.n); a leaf-board size whose
    # layout needs a larger class than declared is skipped, not failed
    k, classes = cfg["k"], {int(n): c for n, c in cfg["classes"].items()}
    if tree_n not in classes:
        raise Reject(f"no class known for L_chain({tree_n}) (config classes)")
    if k < classes[tree_n]:
        raise Reject(f"the declared class k = {k} is below the class {classes[tree_n]} of the benchmark layout "
                     f"L_chain({tree_n}): no board can be run")
    chains, skipped = [tree_n] * tree_leaves, {}
    if "L" in boards:
        for n, count in sorted(cfg["leafboard"].items(), key=lambda kv: int(kv[0])):
            n = int(n)
            if n not in classes:
                raise Reject(f"no class known for L_chain({n}) (config classes)")
            if classes[n] > k:
                skipped[str(n)] = f"L_chain({n}) needs class {classes[n]} > declared k = {k}"
                log(f"board L: skipping n = {n} ({skipped[str(n)]})")
                continue
            chains += [n] * count
    secrets = [l.strip() for l in open(secrets_path) if l.strip()]
    if len(secrets) < len(chains) or not all(re.fullmatch(r"[0-9a-f]{64}", s) for s in secrets):
        raise Reject(f"{secrets_path}: expected at least {len(chains)} lines of 64 lowercase hex digits")
    secrets = [bytes.fromhex(s) for s in secrets[:len(chains)]]
    xs = [chain_stmt(s, n) for s, n in zip(secrets, chains)]
    res["instances"] = {"k": k, "chains": len(chains), "n": sorted(set(chains)), "skipped": skipped,
                        "tree": {"n": tree_n, "leaves": tree_leaves, "depth": depth},
                        "secrets_sha256": hashlib.sha256(b"".join(secrets)).hexdigest()}

    # 0. the native prover's build (untimed, sandboxed, budget prover_build_s)
    if cfg["prover_build"]:
        b = cfg["prover_build"]
        rc, wall, _ = R.run(b["cmd"], b["dir"], cfg["budgets"]["prover_build_s"], "prover build")
        if rc != 0:
            raise Reject(f"prover build failed (exit {rc})")
        res["prover_build_s"] = wall

    # 2. indexing (untimed)
    idx_budget = cfg["budgets"]["index_total_s"]
    keys, index_log = {}, []
    def index(name, layout_path):
        nonlocal idx_budget
        d = R.stage(f"index-{name}", {}, layout_path)
        rc, wall, rss = R.run(cfg["index"] + ["layout.json", "vkc.bin"], d, max(idx_budget, 0.001), f"index {name}")
        idx_budget -= wall
        if rc != 0 or not os.path.exists(os.path.join(d, "vkc.bin")):
            raise Reject(f"index {name}: failed (exit {rc})")
        vkc = open(os.path.join(d, "vkc.bin"), "rb").read()
        printed = open(os.path.join(d, ".stdout")).read().strip()
        if printed != H(h, vkc).hex():
            raise Reject(f"index {name}: printed digest {printed!r} is not the hash of its key bytes")
        index_log.append({"layout": name, "wall_s": wall, "maxrss_kb": rss, "key_bytes": len(vkc), "digest": printed})
        R.cleanup(d)
        return vkc
    layouts = {}
    for n in sorted(set(chains)):
        p = os.path.join(workdir, f"L_chain-{n}.layout.json")
        subprocess.run([sys.executable, "-I", cfg["gen"], "layout", "--n", str(n), p], check=True,
                       stdout=subprocess.DEVNULL)
        layouts[n] = p
        keys[n] = index(f"L_chain({n})", p)
    if tree_bs:
        try:
            keys["C"] = index("C_V", cfg["layouts"]["C"])
            claim = cfg["claim"] or {}
            for what, mine in (("digestC", H(h, keys["C"]).hex()), ("digestL", H(h, keys[tree_n]).hex())):
                if claim.get(what) != mine:
                    raise Reject(f"declared {what} {claim.get(what)!r} differs from the indexer's {mine} (S5-A13)")
        except Reject as e:
            fail(tree_bs, str(e))
    res["indexing"] = {"runs": index_log, "total_s": sum(r["wall_s"] for r in index_log)}

    caps = cfg["caps"]
    runs = []
    for rep in range(cfg["repeats"]):
        if all(b in failed for b in boards):
            break
        run = {"leaves": [], "wrap": [], "nodes": [], "root": None}
        proofs = []
        # 3. leaves: the tree chains (every board) first, then the leaf board's own chains
        for i, (s, n, x) in enumerate(zip(secrets, chains, xs)):
            tree_chain = i < tree_leaves
            if not tree_chain and "L" in failed:
                continue
            what = f"run {rep} leaf {i} (n = {n})"
            try:
                proof, pw, prss = R.prove(f"r{rep}-leaf{i}", LEAF, layouts[n],
                                          {"vkc.bin": keys[n], "stmt.bin": stmt_bytes(x), "secret.hex": s.hex() + "\n"},
                                          cfg["budgets"]["leaf_s"], what)
                if len(proof) > caps["tape_L"] and "L" in boards:
                    fail({"L"}, f"{what}: proof of {len(proof)} bytes above the board-L cap {caps['tape_L']} (S7-A3)")
                if not ((tree_chain and tree_bs) or "L" not in failed):
                    continue                                  # no board still needs this proof
                vw, vrss = R.verify(keys[n], x, proof, cfg["budgets"]["verify_s"], what, caps["tape_R"])
            except Reject as e:
                if tree_chain:
                    raise                                     # every board uses the tree chains
                fail({"L"}, str(e))
                continue
            run["leaves"].append({"chain": i, "n": n, **step_record(pw, prss, vw, vrss, proof)})
            proofs.append(proof)
        # 4. tree, 5. root (boards R and W)
        if tree_bs and not (tree_bs <= set(failed)):
            try:
                tree(R, cfg, h, keys, tree_n, depth, xs[:tree_leaves], proofs[:tree_leaves], rep, run)
            except Reject as e:
                fail(tree_bs, str(e))
        scores = lambda rs: median([r["score_s"] for r in rs])
        run["S_leaf"] = scores(run["leaves"])
        run["S_leaf_by_n"] = {str(n): scores([r for r in run["leaves"] if r["n"] == n]) for n in sorted(set(chains))}
        run["S_wrap"], run["S_rec"] = scores(run["wrap"]), scores(run["nodes"])
        runs.append(run)
        res["runs"] = runs
        log(f"run {rep}: S_leaf {run['S_leaf']}, S_wrap {run['S_wrap']}, S_rec {run['S_rec']} "
            f"({time.perf_counter() - R.t0:.1f} s elapsed)")

    # 6. per-board verdicts and scores: medians of per-run medians
    out = {}
    med = lambda key: median([r[key] for r in runs if r[key] is not None])
    if "L" in boards:
        out["L"] = {"S_leaf": med("S_leaf"),
                    "S_leaf_by_n": {n: median([r["S_leaf_by_n"][n] for r in runs if r["S_leaf_by_n"].get(n) is not None])
                                    for n in runs[0]["S_leaf_by_n"]} if runs else {},
                    "skipped": skipped, "proof_cap": caps["tape_L"],
                    "max_proof_bytes": max((l["proof_bytes"] for r in runs for l in r["leaves"]), default=None)}
    if tree_bs:
        out["R"] = {"S_rec": med("S_rec"), "steps_per_run": len(runs[0]["nodes"]) if runs else 0}
        out["W"] = {"S_wrap": med("S_wrap"), "steps_per_run": len(runs[0]["wrap"]) if runs else 0}
    for b, v in out.items():
        v["verdict"], v["reason"] = ("REJECT", failed[b]) if b in failed else ("ACCEPT", None)

    # 7. DoS column (unranked): random tapes under the leaf key and the first statement
    dos = cfg["dos"]
    if dos["tapes"]:
        rng = random.Random(dos["seed"]) if dos["seed"] is not None else random.SystemRandom()
        worst, accepted = 0.0, 0
        for i in range(dos["tapes"]):
            t = rng.randbytes(rng.randrange(dos["max_len"] + 1))
            rc, wall, _ = R.run_verify("dos", keys[tree_n], xs[0], t, cfg["budgets"]["verify_s"], f"DoS tape {i}")
            if rc not in (0, 1):
                raise Reject(f"DoS tape {i}: verify crashed (exit {rc})")
            accepted += rc == 0
            worst = max(worst, wall)
        out["DoS"] = {"tapes": dos["tapes"], "max_verify_s": worst, "accepted": accepted}
        if accepted:
            raise Reject(f"DoS: {accepted} random tapes were accepted")
    res["scores"] = out


def tree(R, cfg, h, keys, tree_n, depth, xs, proofs, rep, run):
    """§6.3 steps 4-5: the wrap steps, the node steps level by level, the root check."""
    caps = cfg["caps"]
    vkC, vkL = keys["C"], keys[tree_n]
    dC, dL = H(h, vkC), H(h, vkL)
    level = [(LEAF, x, p) for x, p in zip(xs, proofs)]
    lv = 1
    while len(level) > 1:
        nxt = []
        for j in range(0, len(level), 2):
            (t1, x1, p1), (t2, x2, p2) = level[j], level[j + 1]
            x = node_stmt(h, dC, dL, t1, t2, x1, x2)
            what = f"run {rep} level {lv} step {j // 2}"
            files = {"vkc.bin": vkC, "vkC.bin": vkC, "vkL.bin": vkL, "stmt.bin": stmt_bytes(x),
                     "child1.stmt": stmt_bytes(x1), "child1.proof": p1, "child1.tag": t1 + "\n",
                     "child2.stmt": stmt_bytes(x2), "child2.proof": p2, "child2.tag": t2 + "\n"}
            proof, pw, prss = R.prove(f"r{rep}-l{lv}-s{j // 2}", NODE, cfg["layouts"]["C"], files,
                                      cfg["budgets"]["step_s"], what)
            vw, vrss = R.verify(vkC, x, proof, cfg["budgets"]["verify_s"], what, caps["tape_R"])
            (run["wrap"] if lv == 1 else run["nodes"]).append(
                {"level": lv, "step": j // 2, "tags": [t1, t2], **step_record(pw, prss, vw, vrss, proof)})
            nxt.append((NODE, x, proof))
        level, lv = nxt, lv + 1
    (_, xr, pr), = level
    if tree_root(h, dC, dL, depth, xs) != xr:
        raise Reject(f"run {rep}: the root statement is not treeRoot of the leaf statements (rootOK)")
    vw, vrss = R.verify(vkC, xr, pr, cfg["budgets"]["root_s"], f"run {rep} root", caps["tape_R"])
    run["root"] = {"verify_s": vw, "verify_maxrss_kb": vrss, "proof_bytes": len(pr), "stmt": stmt_bytes(xr).hex()}


def machine_info():
    info = {"hostname": platform.node(), "kernel": platform.release(), "machine": platform.machine(),
            "python": platform.python_version(), "cpus": os.cpu_count()}
    try:
        for line in open("/proc/cpuinfo"):
            if line.startswith("model name"):
                info["cpu"] = line.split(":", 1)[1].strip(); break
        for line in open("/proc/meminfo"):
            if line.startswith("MemTotal"):
                info["mem_kb"] = int(line.split()[1]); break
    except OSError:
        pass
    info["glibc"] = " ".join(platform.libc_ver())
    return info


def load_config(path):
    cfg = json.load(open(path))
    out = json.loads(json.dumps(DEFAULTS))
    for k, v in cfg.items():
        if k not in DEFAULTS and k not in ("verify", "index", "prover", "gen", "layouts", "keep", "k"):
            raise SystemExit(f"run-benchmark: unknown config key {k!r}")
        if k == "cfg" and set(v) - {"hash"}:
            raise SystemExit(f"run-benchmark: cfg takes only \"hash\" (the arity is the submission's, S6b-m5)")
        if isinstance(v, dict) and isinstance(out.get(k), dict) and k not in ("leafboard", "classes"):
            out[k].update(v)
        else:
            out[k] = v
    for k in ("verify", "index", "prover", "gen", "k"):
        if k not in out:
            raise SystemExit(f"run-benchmark: config needs {k!r}")
    for k in ("verify", "index", "prover"):
        if isinstance(out[k], str):
            out[k] = [out[k]]
    if "R" in out["boards"] and not (out.get("layouts") or {}).get("C"):
        raise SystemExit("run-benchmark: board R needs layouts.C (the submitted C_V JSON)")
    return out


def preflight(cfg):
    """`run` fails closed (S6b-M1, S6b-m1): no evaluation without the sandbox and the cgroup."""
    sb = cfg.get("sandbox")
    if not sb or not (os.path.isfile(sb) and os.access(sb, os.X_OK)):
        return (f"no sandbox: the config's \"sandbox\" must name scripts/bwrap-landrun.sh (got {sb!r}); "
                "the runner does not run unsandboxed steps (S6b-M1)")
    try:
        ok = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", "MemoryMax=64M",
                             "-p", "OOMPolicy=continue", "--", "true"],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=30).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        ok = False
    if not ok:
        return ("no memory cgroup: `systemd-run --user --scope -p MemoryMax=… -p OOMPolicy=continue` is unavailable; the runner "
                "caps every step's whole process tree through a cgroup and does not fall back to "
                "per-process accounting (S6b-m1, harness/reference-machine.md)")
    return None


def cmd_run(a):
    cfg = load_config(a.config)
    cfg["keep"] = a.keep or cfg.get("keep", False)
    base = a.workdir or tempfile.mkdtemp(prefix="rf-bench-")
    os.makedirs(base, exist_ok=True)
    workdir = os.path.realpath(tempfile.mkdtemp(prefix="eval-", dir=base))
    res = {"schema": "recursion.fast/bench-result/1", "verdict": None, "reason": None,
           "started": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "machine": machine_info(),
           "config": {k: v for k, v in cfg.items() if k != "claim"}, "claim": cfg["claim"], "workdir": workdir}
    log = lambda m: print(f"run-benchmark: {m}", flush=True)
    t0 = time.perf_counter()
    try:
        bad = preflight(cfg)
        if bad:
            raise Reject(bad)
        evaluate(cfg, os.path.realpath(a.secrets), workdir, res, log)
        boards = {b: v for b, v in res["scores"].items() if "verdict" in v}
        ok = [b for b, v in boards.items() if v["verdict"] == "ACCEPT"]
        res["verdict"] = "ACCEPT" if ok else "REJECT"
        res["accepted_boards"] = ok
        if not ok:
            res["reason"] = "; ".join(f"board {b}: {v['reason']}" for b, v in boards.items())
    except Reject as e:
        res["verdict"], res["reason"] = "REJECT", str(e)
    res["elapsed_s"] = time.perf_counter() - t0
    with open(a.out, "w") as f:
        json.dump(res, f, indent=1)
    if not cfg["keep"]:
        shutil.rmtree(workdir, ignore_errors=True)
    log(f"{res['verdict']}" + (f" ({res['reason']})" if res["reason"] else "") + f" in {res['elapsed_s']:.1f} s; {a.out}")
    for b, sc in (res.get("scores") or {}).items():
        log(f"board {b}: {sc}")
    return 0 if res["verdict"] == "ACCEPT" else 1


def cmd_secrets(a):
    fd = os.open(a.out, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        for _ in range(a.count):
            f.write(os.urandom(32).hex() + "\n")
    return 0


def is_record(new, standing, margin=0.03):
    """The record rule (DESIGN §6.4): a score (lower is better) is a new record iff there is no
    standing record or it beats the standing one by at least `margin` (relative):
    `new <= (1 - margin) * standing`."""
    if not (0 <= margin < 1):
        raise ValueError("margin must be in [0, 1)")
    return standing is None or new <= (1 - margin) * standing


def cmd_record(a):
    r = is_record(a.new, a.standing, a.margin)
    print(f"{'RECORD' if r else 'not a record'}: {a.new} vs standing {a.standing} (margin {a.margin:.1%})")
    return 0 if r else 1


def cmd_selftest(a):
    """Cross-check the re-implemented statement functions against the kernel-checked values of
    Controls/RecursionData.lean (`xN`, `xR`, `xT`: `nodeStmt_kat`, `treeKat`, `rootOK_xT`) and the
    chain statement against gen-chain-layout.py; and the record rule."""
    src = open(a.lean_data).read()
    def lean_words(name):
        m = re.search(rf"def {name} : Stmt := stmtOfWords\s*\[([^\]]*)\]", src)
        return [int(w, 16) for w in re.findall(r"0x([0-9a-f]+)", m.group(1))]
    xN, xR, xT = lean_words("xN"), lean_words("xR"), lean_words("xT")
    # the key vkc2 of Controls/CompileToy.lean: VK = [0x1234], index root of [100], [101] at arity 2
    leafh = lambda e: hashlib.blake2s(e.to_bytes(8, "little")).digest()
    root = hashlib.blake2s(leafh(100) + leafh(101)).digest()
    vkc2 = (0x1234).to_bytes(8, "little") + root
    D = H("blake2s", vkc2)
    assert D.hex().startswith("0f4c678b"), D.hex()              # digest_kat
    x0 = [(i * 0x0101) % U64 for i in range(32)]
    x1 = list(x0); x1[31] ^= 1
    ok = []
    ok.append(("nodeStmt_kat (xN)", node_stmt("blake2s", D, D, LEAF, LEAF, x0, x1) == xN))
    ok.append(("xR (node, leaf)", node_stmt("blake2s", D, D, NODE, LEAF, xN, x0) == xR))
    ok.append(("treeKat (xT)", node_stmt("blake2s", D, D, NODE, NODE, xN, xN) == xT))
    ok.append(("rootOK_xT", tree_root("blake2s", D, D, 2, [x0, x1, x0, x1]) == xT))
    ok.append(("rootOK_leaf", tree_root("blake2s", D, D, 2, [x0, x1, x0, x1]) != x0))
    ok.append(("rootOK_odd", tree_root("blake2s", D, D, 2, [x0, x1, x0]) is None))
    ok.append(("depth mismatch", tree_root("blake2s", D, D, 1, [x0, x1, x0, x1]) is None))
    ok.append(("empty", tree_root("blake2s", D, D, 1, []) is None))
    if a.gen:
        with tempfile.TemporaryDirectory() as t:
            s = bytes(range(32))
            for n in (1, 4):
                subprocess.run([sys.executable, "-I", a.gen, "witness", "--n", str(n), "--secret-file", "-",
                                os.path.join(t, "w.json"), os.path.join(t, "x.json")],
                               input=(s.hex() + "\n").encode(), check=True, stdout=subprocess.DEVNULL)
                want = [int(v, 16) for v in json.load(open(os.path.join(t, "x.json")))["x"]]
                ok.append((f"chain statement n = {n} (gen-chain-layout.py)", chain_stmt(s, n) == want))
    ok.append(("record rule", is_record(97.0, 100.0) and not is_record(97.01, 100.0) and is_record(5.0, None)))
    for name, good in ok:
        print(f"selftest: {name}: {'OK' if good else 'FAIL'}")
    return 0 if all(g for _, g in ok) else 1


